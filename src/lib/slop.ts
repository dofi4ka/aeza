export function rngFor(seed: string | number): Rng {
  return mulberry32(typeof seed === 'number' ? seed : hashStr(seed))
}

export function slopSentence(r: Rng = Math.random) {
  return `${pick(OPENERS, r)} ${pick(SUBJECTS, r)} — это ${pick(NOT_JUST, r)} ${pick(NOUNS, r)}, ${pick(BUT, r)}. ${pick(CLOSERS, r)}`
}

export function slopParagraph(seed: string | number, n = 3) {
  const r = rngFor(seed)
  return Array.from({ length: n }, () => slopSentence(r)).join(' ')
}

/** «Хостинг» → «Хостинг. Хостинг нового поколения. Хостинг.» */
export function echo(s: string, times = 3) {
  return Array.from({ length: times }, () => s).join(' ')
}

