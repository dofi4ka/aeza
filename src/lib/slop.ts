export function aiAnswer(q: string): string {
  const r = Math.random
  const rule = RULES.find((x) => x.re.test(q))
  let body = rule ? pick(rule.answers, r) : `Отличный вопрос! 🙌\n\n${slopSentence(r)}\n\n${slopSentence(r)}`
  if (r() < 0.45) {
    const first = body.split(/(?<=[.!?])\s/)[0]
    body += `\n\n**Подытожим:** ${first}`
  }
  const tails = [
    'Хотите, я повторю это ещё раз? 🔁',
    'Надеюсь, это помогло! Если есть ещё вопросы — задавайте! 😊',
    'Могу ли я ещё чем-нибудь помочь вам помочь? 🙏',
    'Важно: это не финансовый, не технический и не какой-либо совет. ⚠️',
  ]
  return `${body}\n\n${pick(tails, r)}`
}
